"""Regenerate the sources table in README.md from the database (run by pre-commit)."""

from pathlib import Path

from django.conf import settings
from django.core.management.base import BaseCommand
from django.db import OperationalError
from django.db.models import Count, Q

START = "<!-- sources-table:start -->"
END = "<!-- sources-table:end -->"


def render() -> str:
    from census.models import Dataset, Source
    from places.models import Jurisdiction
    from records.models import Record
    from search.models import NameEntry

    sources = (
        Source.objects.filter(platform__in=Source.CRAWLABLE)
        .select_related("publisher")
        .order_by("name")
        .annotate(
            n=Count("datasets", filter=Q(datasets__removed_at=None)),
            watched=Count("datasets", filter=Q(datasets__status="watched")),
        )
    )
    lines = [
        "<!-- Generated by `manage.py build_readme`. Don't edit by hand. -->",
        "",
        "| Source | Publisher | Platform | Datasets | Watched | Last crawled |",
        "| --- | --- | --- | --: | --: | --- |",
    ]
    for s in sources:
        crawled = s.last_crawled_at.date().isoformat() if s.last_crawled_at else "never"
        lines.append(
            f"| [{s.name}]({s.url}) | {s.publisher or ''} | {s.get_platform_display()} "
            f"| {s.n:,} | {s.watched or ''} | {crawled} |"
        )
    live = Dataset.objects.filter(removed_at=None)
    features = Record.objects.filter(recordset__gis_dataset__isnull=False).count()
    counties = (
        Jurisdiction.objects.filter(
            kind="county", datasets__isnull=False, datasets__removed_at=None
        )
        .distinct()
        .count()
    )
    lines += [
        "",
        f"{live.count():,} datasets from {len(sources)} sources, "
        f"covering {counties} of 66 counties. "
        f"{features:,} features archived; "
        f"{NameEntry.objects.count():,} names indexed.",
    ]
    beacon = Source.objects.filter(platform=Source.Platform.BEACON).order_by("name")
    if beacon:
        links = ", ".join(f"[{s.name.removesuffix(' (Beacon)')}]({s.url})" for s in beacon)
        lines += ["", f"Listed but not crawled, on Schneider Beacon ({len(beacon)}): {links}."]
    return "\n".join(lines)


class Command(BaseCommand):
    help = "Regenerate the sources table in README.md from the database"

    def add_arguments(self, parser):
        parser.add_argument("--readme", type=Path, default=Path(settings.BASE_DIR) / "README.md")

    def handle(self, *args, readme: Path, **options):
        from census.models import Source

        try:
            if not Source.objects.exists():
                # A fresh or CI database: keep the table from the real one
                self.stderr.write("Skipping README table: no sources in this database")
                return
            table = render()
        except OperationalError as e:
            self.stderr.write(f"Skipping README table, database unavailable: {e}")
            return
        text = readme.read_text()
        start, end = text.find(START), text.find(END)
        if start == -1 or end == -1:
            self.stderr.write(f"{readme} has no {START} / {END} markers")
            return
        new = f"{text[: start + len(START)]}\n{table}\n{text[end:]}"
        if new != text:
            readme.write_text(new)
            self.stdout.write(f"Updated sources table in {readme}")
